"""Regenerate app/src/glyphs.ts: the halo's characters as SVG outlines.

The MCP app runs in a host sandbox whose CSP the host decides, so it cannot
count on loading a font, and system CJK fonts differ per machine or are
missing (boxes on minimal Linux, sans fallbacks on Android and Windows). The
two dozen characters the UI draws ship as paths instead.

The characters are traditional forms, as in Kumārajīva's Lotus Sutra. Fetch
a subset of Noto Serif TC (SIL OFL 1.1) holding just these characters:

    CHARS=$(python3 -c 'import sys,urllib.parse;sys.path.insert(0,"app/scripts");import glyphs;print(urllib.parse.quote(glyphs.CHARS))')
    curl -fsS "https://fonts.googleapis.com/css2?family=Noto+Serif+TC:wght@500&text=$CHARS"
    # download the url(...) it names, then:
    uv run --with fonttools python -I app/scripts/glyphs.py <font.ttf> app/src/glyphs.ts
"""

import sys

CHARS = "發開行示方便權直漸頓悟轉融出入觀照證淨圓止蓮空"


def main(src: str, out: str) -> None:
    from fontTools.pens.svgPathPen import SVGPathPen
    from fontTools.pens.transformPen import TransformPen
    from fontTools.ttLib import TTFont

    font = TTFont(src)
    em = font["head"].unitsPerEm
    ascent = font["OS/2"].sTypoAscender
    cmap = font.getBestCmap()
    glyphs = font.getGlyphSet()
    notice = font["name"].getDebugName(0) or ""
    family = font["name"].getDebugName(1) or "unknown"

    rows = []
    for ch in CHARS:
        name = cmap.get(ord(ch))
        if name is None:
            sys.exit(f"{ch} is missing from {src}")
        pen = SVGPathPen(glyphs, ntos=lambda v: str(round(v)))
        glyphs[name].draw(TransformPen(pen, (1, 0, 0, -1, 0, ascent)))
        rows.append(f'  "{ch}": [{glyphs[name].width}, "{pen.getCommands()}"],')

    body = "\n".join(rows)
    with open(out, "w", encoding="utf-8") as f:
        f.write(
            "// Generated by app/scripts/glyphs.py; do not edit.\n"
            f"// Outlines from {family}. {notice}\n"
            "// SIL Open Font License 1.1: https://openfontlicense.org\n\n"
            f"export const EM = {em};\n\n"
            "export const GLYPHS: Record<string, readonly [advance: number, d: string]> = {\n"
            f"{body}\n"
            "};\n"
        )


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
